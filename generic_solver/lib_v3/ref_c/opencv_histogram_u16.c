/* Public OpenCV calcHist_<ushort>, one channel, 256 uniform bins over
 * [0,65536). floor(pixel/256) is exactly pixel>>8 for unsigned 16-bit values.
 * Initialize and emit the single integer histogram without Mat containers.
 */
#include <stdint.h>
void NETLIB_SPEC(int h,int w,const uint16_t input[h][w],OUTPUT_TYPE output[256]) {
  for(int b=0;b<256;++b) output[b]=0;
  for(int y=0;y<h;++y) for(int x=0;x<w;++x)
    output[(uint32_t)input[y][x]>>8]++;
}
